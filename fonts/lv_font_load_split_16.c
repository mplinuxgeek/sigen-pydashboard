/* Merges Montserrat glyphs (just digits, '%' and space -- the only
 * text this font is ever asked to render) with three MDI icon glyphs
 * (solar-power, home-battery-outline, transmission-tower) into ONE
 * lv_font_t, so a single lv_label_t can mix icon+number inline (e.g.
 * MDI16_SOLAR "7%") the way lv_font_mdi_24.c's icons can't alongside
 * lv_font_montserrat_16 -- LVGL only looks up glyphs in the one font a
 * label is given, and merging via lv_font_conv's multi "--font" support
 * is the supported way around that, rather than a fallback-font hack
 * (LVGL's built-in fonts merge FontAwesome symbols into Montserrat the
 * same way, for the same reason). See dashboard_ui.c's
 * set_covered_label() for the only place this font is used, and
 * lv_font_mdi_24.c for why the private-use codepoints below are
 * E010-E012, not E001-E003 -- this is a different lv_font_t with its
 * own separate codepoint space, but distinct numbers avoid the two
 * fonts' icon macros ever being confused with each other. Every other
 * file in this project includes lvgl.h directly (the component exposes
 * its root as an include dir) -- lv_font_conv's generated
 * "lvgl/lvgl.h" fallback doesn't resolve here, so this is hardcoded
 * rather than left conditional on LV_LVGL_H_INCLUDE_SIMPLE (which
 * nothing in this project defines). */
#include "lvgl/lvgl.h"

